# Keyword is a reserved word in Python that cannot be used as an identifier (variable name, function name, etc.). Keywords are predefined and have special meanings in the language.
# Here are some examples of keywords in Python:
# False      await      else       import     pass
# None       break      except     in         raise
# True       class      finally    is         return
# and        continue   for        lambda     try
# as         def        from       nonlocal   while


# Identifiers naming rules:
# 1. An identifier can be a combination of letters in lowercase (a to z) or uppercase (A to Z) or digits (0 to 9) or an underscore (_).
# Example: myVar, var_1, _my_var, myVar2


# 2. An identifier cannot start with a digit.
# Example: 1var, 2myVar, 3_var (invalid identifiers)


# 3. Keywords cannot be used as identifiers. 
# Example: if, else, while, for, def (invalid identifiers)