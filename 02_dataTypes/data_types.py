# Integer
print("Integer:")
print(7)

# Float
print("Float:")
print(3.14)

# String
print("String:")
print("Hello, World!")

# Boolean
print("Boolean:")
print(True)
print(False)

# Complex
print("Complex:")
print(2 + 3j) #real part is 2, imaginary part is 3

# List, similar to array in other languages, can hold multiple data types
print("List:")
my_list = [1, 2, 3, 4, 5]
print(my_list)

# Tuple, similar to list but immutable (cannot be changed)
print("Tuple:")
my_tuple = (1, 2, 3, 4, 5)
print(my_tuple)

# Set, unordered collection of unique elements
print("Set:")
my_set = {1, 2, 3, 4, 5}
print(my_set)

# Dictionary, key-value pairs
print("Dictionary:")
my_dict = {"name": "Alice", "age": 30, "city": "New York"}
print(my_dict)

